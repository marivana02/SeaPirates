let currentLang = localStorage.getItem('sp_lang') || 'en';

function t(key, params = {}) {
  const lang = I18N_DATA[currentLang] || I18N_DATA['en'];
  let text = lang[key] || I18N_DATA['en'][key] || key;
  
  // Replace params like {name}
  Object.keys(params).forEach(p => {
    text = text.replace(`{${p}}`, params[p]);
  });
  
  return text;
}

function setLanguage(lang) {
  if (I18N_DATA[lang]) {
    currentLang = lang;
    localStorage.setItem('sp_lang', lang);
    applyI18n();
    // Dispatch event so other components can react
    window.dispatchEvent(new Event('languageChanged'));
    return true;
  }
  return false;
}

function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key) {
      const target = el.querySelector('[data-i18n-text]') || el;
      target.innerHTML = t(key);
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) el.placeholder = t(key);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (key) el.title = t(key);
  });
}

// Global olarak erişilebilir yap
window.t = t;
window.setLanguage = setLanguage;
window.applyI18n = applyI18n;
Object.defineProperty(window, 'currentLang', { get: () => currentLang, configurable: true });

// Sayfa yüklendiğinde otomatik uygula
document.addEventListener('DOMContentLoaded', applyI18n);
